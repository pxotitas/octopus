//! Waybar's config and layout CSS, generated from octopus.toml [bar].

pub mod art;
pub mod modules;
pub mod presets;

use serde_json::{json, Map, Value};

use crate::config::Bar;
use crate::exec;

/// Radius of the flush bar's inward corners.
const CONCAVE: u32 = 14;

/// The flush bar: square against the screen's edge, with two inward corners
/// where it meets the top and the bottom, so the rest of the screen reads as
/// a rounded card. Drawn with gradients, since GTK 3 has no masks.
fn flush_css(bar: &Bar) -> String {
    let (w, r) = (bar.width, CONCAVE);
    let fill = "@surface_container";
    let (body, top, bottom, pad, top_at, bottom_at) = if bar.right() {
        ("right top", "0% 100%", "0% 0%", "padding-left", "0 0".to_owned(), "0 100%".to_owned())
    } else {
        ("left top", "100% 100%", "100% 0%", "padding-right", format!("{w}px 0"), format!("{w}px 100%"))
    };
    format!(
        "window#waybar > box {{ border-radius: 0; {pad}: {r}px; background-color: transparent; \
background-image: linear-gradient({fill}, {fill}), \
radial-gradient(circle at {top}, transparent {inner}px, {fill} {r}px), \
radial-gradient(circle at {bottom}, transparent {inner}px, {fill} {r}px); \
background-size: {w}px 100%, {r}px {r}px, {r}px {r}px; \
background-position: {body}, {top_at}, {bottom_at}; background-repeat: no-repeat; }}\n",
        inner = r as f64 - 0.5,
    )
}

/// Waybar's config, generated from octopus.toml so the settings window can
/// move things around.
pub fn waybar_config(bar: &Bar) -> String {
    let mut config = Map::new();
    let zone = |list: &[String], config: &mut Map<String, Value>| -> Vec<Value> {
        list.iter()
            .filter_map(|id| modules::waybar(id, &bar.module(id), bar, config))
            .map(Value::from)
            .collect()
    };
    let top = zone(&bar.top, &mut config);
    let center = zone(&bar.center, &mut config);
    let bottom = zone(&bar.bottom, &mut config);

    let flush = bar.style == "flush";
    let width = if flush { bar.width + CONCAVE } else { bar.width };
    let (top_gap, bottom_gap, edge_gap) = if flush { (0, 0, 0) } else { (bar.margin_top, bar.margin_bottom, bar.margin_edge) };
    config.insert("layer".into(), json!(bar.layer));
    config.insert("exclusive".into(), json!(bar.exclusive));
    config.insert("position".into(), json!(bar.position));
    config.insert("width".into(), json!(width));
    config.insert("margin-top".into(), json!(top_gap));
    config.insert("margin-bottom".into(), json!(bottom_gap));
    config.insert(if bar.right() { "margin-right" } else { "margin-left" }.into(), json!(edge_gap));
    config.insert("spacing".into(), json!(bar.spacing));
    config.insert("reload_style_on_change".into(), json!(true));
    config.insert("modules-left".into(), Value::Array(top));
    config.insert("modules-center".into(), Value::Array(center));
    config.insert("modules-right".into(), Value::Array(bottom));

    let mut text = String::from("// Generated by octopus from octopus.toml [bar]; change it in `octopus settings`.\n");
    text.push_str(&serde_json::to_string_pretty(&Value::Object(config)).unwrap_or_default());
    text.push('\n');
    text
}

/// Everything in the bar that depends on its width: each module fills the
/// column (margins + min-width = width) so its glyph sits centered. Then
/// each module's own look.
pub fn layout_css(bar: &Bar) -> String {
    let w = bar.width as i32;
    let side = |inner: i32| ((w - inner) / 2).max(0);
    let mut css = format!(
        "/* generated by octopus from octopus.toml [bar] */\n\
#custom-launcher, #custom-control-center, #custom-tray, #tray-arrow, #network, #bluetooth, #wireplumber, #custom-power, \
#cpu, #memory, #temperature, #backlight, #idle_inhibitor, #mpris, #custom-notifications {{ min-width: {icon}px; margin-left: 8px; margin-right: 8px; }}\n\
#workspaces button {{ margin: 3px {ws}px; }}\n\
#clock {{ margin-left: {clock}px; margin-right: {clock}px; }}\n\
#custom-battery {{ margin: 4px {bat}px 0; }}\n\
#battery {{ margin-left: {pct}px; margin-right: {pct}px; }}\n{flush}",
        flush = if bar.style == "flush" { flush_css(bar) } else { String::new() },
        icon = (w - 16).max(0),
        ws = side(10),
        clock = side(32),
        bat = side(14),
        pct = side(24),
    );
    for id in bar.placed() {
        css.push_str(&scoped(&modules::css(id, &bar.module(id), bar)));
    }
    css
}

/// layout.css comes before style.css, so a module's own look needs more
/// weight than style.css' rules to win.
fn scoped(css: &str) -> String {
    css.lines()
        .map(|line| match line.split_once(" {") {
            Some((selectors, rest)) => {
                let selectors: Vec<String> = selectors.split(", ").map(|s| format!("window#waybar {}", s.trim())).collect();
                format!("{} {{{rest}\n", selectors.join(", "))
            }
            None => format!("{line}\n"),
        })
        .collect()
}

/// Writes Waybar's generated files and asks it to reload when they changed.
pub fn apply(bar: &Bar) {
    let dir = gtk::glib::user_config_dir().join("waybar");
    let _ = std::fs::create_dir_all(&dir);
    let mut changed = art::shapes(bar);
    for (name, text) in [("config.jsonc", waybar_config(bar)), ("layout.css", layout_css(bar))] {
        let path = dir.join(name);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            changed |= std::fs::write(path, text).is_ok();
        }
    }
    if changed {
        exec::spawn("pkill", &["-SIGUSR2", "-x", "waybar"]);
    }
}

#[cfg(test)]
mod tests {
    fn parse(text: &str) -> serde_json::Value {
        let body: String = text.lines().filter(|l| !l.trim_start().starts_with("//")).collect::<Vec<_>>().join("\n");
        serde_json::from_str(&body).expect("valid json")
    }

    #[test]
    fn flush_css_mentions_both_corners() {
        let mut bar = crate::config::Bar::default();
        bar.style = "flush".into();
        assert!(super::layout_css(&bar).contains("radial-gradient(circle at 100% 100%"));
    }

    #[test]
    fn default_config_is_valid_json() {
        let bar = crate::config::Bar::default();
        let parsed = parse(&super::waybar_config(&bar));
        assert_eq!(parsed["width"], 52);
        assert_eq!(parsed["modules-right"][2], "group/controls");
    }

    #[test]
    fn custom_modules_and_shapes() {
        use crate::config::{Custom, Module};
        let mut bar = crate::config::Bar::default();
        bar.custom.push(Custom { id: "user-1".into(), exec: "date +%S".into(), ..Custom::default() });
        bar.bottom.insert(0, "user-1".into());
        bar.bottom.insert(0, "cpu".into());
        bar.modules.insert("cpu".into(), Module { shape: "flower".into(), background: "primary".into(), ..Module::default_for("cpu") });
        bar.modules.insert("user-1".into(), Module { text: true, ..Module::default() });
        bar.modules.insert("logo".into(), Module { variant: "octopus".into(), ..Module::default_for("logo") });
        bar.modules.insert("workspaces".into(), Module { variant: "bars".into(), ..Module::default() });
        let parsed = parse(&super::waybar_config(&bar));
        assert_eq!(parsed["modules-right"][0], "cpu");
        assert_eq!(parsed["modules-right"][1], "custom/user-1");
        assert_eq!(parsed["custom/user-1"]["exec"], "date +%S");
        assert_eq!(parsed["custom/launcher"]["format"], " ");
        let css = super::layout_css(&bar);
        assert!(css.contains("url(\"art/cpu.svg\")"));
        assert!(css.contains("url(\"art/logo.svg\")"));
        assert!(css.contains("window#waybar #custom-user-1"));
        assert!(css.contains("min-width: 4px"));
        assert!(crate::widgets::shape::svg_path(crate::widgets::shape::Kind::Flower, 100.0).starts_with("M50.00,0.00"));
    }

    #[test]
    fn every_module_makes_valid_config() {
        let mut bar = crate::config::Bar::default();
        bar.bottom = super::modules::CATALOG.iter().map(|m| m.id.to_owned()).collect();
        let parsed = parse(&super::waybar_config(&bar));
        assert_eq!(parsed["modules-right"].as_array().unwrap().len(), super::modules::CATALOG.len());
        let _ = super::layout_css(&bar);
    }
}
